import type { GoalId, HaveId, LevelId, SuccessId, TimeId } from "./top3-questions";

/**
 * Weekend projects FIND MY TOP 3 can recommend. Each is a specific build with
 * one measurable deliverable — never "learn AI". `startHere` ids resolve via
 * resources.ts (courses and challenges are checked to exist and be available).
 * `gain` describes value without promising income.
 */
export interface WeekendProject {
  id: string;
  title: string;
  area: string;
  summary: string;
  goals: GoalId[];
  levels: LevelId[];
  /** Smallest weekend time budget the project can be finished in. */
  minTime: TimeId;
  /** Every listed resource is needed. "device" means a laptop OR a smartphone. */
  needs: Array<HaveId | "device">;
  /** Optional resources that make it a stronger fit. */
  boosts?: HaveId[];
  success: SuccessId[];
  gain: string;
  deliverable: string;
  plan: {
    friday: PlanStep[];
    saturday: PlanStep[];
    sunday: PlanStep[];
  };
  startHere: string[];
}

/** `tier` 1 = always; 2 = added from 3–5 hours; 3 = added from 6–10 hours. */
export interface PlanStep {
  text: string;
  tier?: 1 | 2 | 3;
}

